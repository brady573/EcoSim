/**
 * Habitat substrate map and the explicit abiotic forcing field.
 *
 * The amendment requires heterogeneous habitats, local niches, succession,
 * competitive displacement, collapse, and restoration as *possible outcomes*
 * rather than forced ones. That needs a substrate with spatially varying
 * capacity, not a uniform field with constant replenishment.
 *
 * HABITAT carries three static, seeded, spatially-correlated properties:
 *   fertility   how much nutrient this cell can hold (its carrying capacity)
 *   shade       how much light reaches it (canopy-like attenuation)
 *   drainage    how fast nutrient recycles/flushes here
 *
 * None of these is "set dressing". fertility bounds producer biomass, shade
 * bounds capture, drainage sets recovery rate. Because producers are sessile
 * and permanently deplete the cell they root in, fertile patches are
 * eventually exhausted, which is the mechanism that makes colonization and
 * succession emergent rather than narrated.
 *
 * LIMITATION (disclosed): the correlations are generated by summing a few
 * sines rather than by a real noise function, to avoid depending on any
 * particular platform's transcendental implementation. That is a determinism
 * choice with a visual cost: the map is smooth and banded rather than
 * irregular.
 */

import { ScalarField } from '../core/field.js';
import { Rng } from '../core/rng.js';

export class HabitatMap {
  /** Nutrient carrying capacity multiplier per cell. */
  readonly fertility: ScalarField;
  /** Light attenuation multiplier per cell. */
  readonly shade: ScalarField;
  /** Nutrient turnover rate multiplier per cell. */
  readonly drainage: ScalarField;

  constructor(
    readonly cols: number,
    readonly rows: number,
    seed: number | string,
  ) {
    this.fertility = new ScalarField('fertility', cols, rows);
    this.shade = new ScalarField('shade', cols, rows);
    this.drainage = new ScalarField('drainage', cols, rows);
    this.generate(seed);
  }

  private generate(seed: number | string): void {
    const rng = new Rng(seed);
    // Independent spatial phases per property, so fertility and shade are not
    // correlated by construction.
    const fp = [rng.nextFloat() * 6.283, rng.nextFloat() * 6.283, rng.nextFloat() * 6.283];
    const sp = [rng.nextFloat() * 6.283, rng.nextFloat() * 6.283, rng.nextFloat() * 6.283];
    const dp = [rng.nextFloat() * 6.283, rng.nextFloat() * 6.283, rng.nextFloat() * 6.283];
    // Wavelengths in cell units: a few overlapping octaves per property.
    const fw = [0.9, 0.28, 0.075];
    const sw = [1.35, 0.4, 0.11];
    const dw = [0.7, 0.21, 0.06];

    for (let y = 0; y < this.rows; y++) {
      for (let x = 0; x < this.cols; x++) {
        const i = y * this.cols + x;

        // Fertility in [0.35, 1.75]: some regions are simply poor.
        let f = 0;
        for (let k = 0; k < 3; k++) {
          const t = (2 * Math.PI * (x * fw[k] + y * fw[k] * 0.62)) / this.cols + fp[k];
          f += Math.sin(t) / (k + 1.6);
        }
        this.fertility.data[i] = 1.05 + f * 0.52;

        // Shade in [0.45, 1.15]: canopy-like attenuation, same construction.
        let s = 0;
        for (let k = 0; k < 3; k++) {
          const t = (2 * Math.PI * (x * sw[k] - y * sw[k] * 0.45)) / this.cols + sp[k];
          s += Math.sin(t) / (k + 1.5);
        }
        this.shade.data[i] = 0.8 + s * 0.28;

        // Drainage in [0.6, 1.6]: how fast a depleted cell recovers.
        let d = 0;
        for (let k = 0; k < 3; k++) {
          const t = (2 * Math.PI * (x * dw[k] + y * dw[k] * 0.9 + x * y * dw[k] * 0.02)) / this.cols + dp[k];
          d += Math.sin(t) / (k + 1.7);
        }
        this.drainage.data[i] = 1.05 + d * 0.42;
      }
    }
  }

  /**
   * Nutrient carrying capacity for a cell. This is the ceiling that makes
   * exhaustion, succession, and collapse reachable.
   */
  capacityAt(index: number, baseCapacity: number): number {
    return baseCapacity * this.fertility.data[index];
  }

  /** Mean fertility, for reporting habitat contrast. */
  meanFertility(): number {
    let s = 0;
    for (let i = 0; i < this.fertility.data.length; i++) s += this.fertility.data[i];
    return s / this.fertility.data.length;
  }

  /** Min/max fertility, to quantify how contrasting the habitats are. */
  fertilityRange(): { min: number; max: number } {
    let min = Infinity;
    let max = -Infinity;
    for (let i = 0; i < this.fertility.data.length; i++) {
      const v = this.fertility.data[i];
      if (v < min) min = v;
      if (v > max) max = v;
    }
    return { min, max };
  }
}